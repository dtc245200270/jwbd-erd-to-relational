CREATE DATABASE IF NOT EXISTS QuanLyKhoHang;
USE QuanLyKhoHang;

CREATE TABLE PHIEUXUAT (SoPX VARCHAR(20) PRIMARY KEY, NgayXuat DATE NOT NULL);
CREATE TABLE VATTU (MaVTU VARCHAR(20) PRIMARY KEY, TenVTU VARCHAR(100) NOT NULL);
CREATE TABLE PHIEUNHAP (SoPN VARCHAR(20) PRIMARY KEY, NgayNhap DATE NOT NULL);
CREATE TABLE NHACC (MaNCC VARCHAR(20) PRIMARY KEY, TenNCC VARCHAR(100) NOT NULL, DiaChi VARCHAR(200));

CREATE TABLE NHACC_SDT (
    MaNCC VARCHAR(20),
    SDT VARCHAR(15),
    PRIMARY KEY (MaNCC, SDT),
    FOREIGN KEY (MaNCC) REFERENCES NHACC(MaNCC)
);

CREATE TABLE DONDH (
    SoDH VARCHAR(20) PRIMARY KEY,
    NgayDH DATE NOT NULL,
    MaNCC VARCHAR(20),
    FOREIGN KEY (MaNCC) REFERENCES NHACC(MaNCC)
);

CREATE TABLE CHITIET_PHIEUXUAT (
    SoPX VARCHAR(20),
    MaVTU VARCHAR(20),
    DGXuat DECIMAL(12, 2) NOT NULL,
    SLXuat INT NOT NULL,
    PRIMARY KEY (SoPX, MaVTU),
    FOREIGN KEY (SoPX) REFERENCES PHIEUXUAT(SoPX),
    FOREIGN KEY (MaVTU) REFERENCES VATTU(MaVTU)
);

CREATE TABLE CHITIET_PHIEUNHAP (
    SoPN VARCHAR(20),
    MaVTU VARCHAR(20),
    DGNhap DECIMAL(12, 2) NOT NULL,
    SLNhap INT NOT NULL,
    PRIMARY KEY (SoPN, MaVTU),
    FOREIGN KEY (SoPN) REFERENCES PHIEUNHAP(SoPN),
    FOREIGN KEY (MaVTU) REFERENCES VATTU(MaVTU)
);

CREATE TABLE CHITIET_DONDH (
    SoDH VARCHAR(20),
    MaVTU VARCHAR(20),
    PRIMARY KEY (SoDH, MaVTU),
    FOREIGN KEY (SoDH) REFERENCES DONDH(SoDH),
    FOREIGN KEY (MaVTU) REFERENCES VATTU(MaVTU)
);
